import { writePNG } from './png.mjs';
import { sheet } from './atlas.mjs';
import { R } from './palette.mjs';
import * as W from './gen/wild.mjs';
const lit = (o) => { const i = o.day.clone(); i.blit(o.glow, 0, 0); return i; };
const a = [];
const add = (name, img) => a.push({ name, img });
add('mush0', W.mushroom(0)); add('mush1', W.mushroom(1)); add('berry0', W.berries(0)); add('berry1', W.berries(1)); add('clay', W.clay());
add('mine', W.mineEntrance()); add('shack', W.shack().day); add('shack-lit', lit(W.shack()));
add('boat', W.rowboat()); add('coop', W.coop().day); add('coop-lit', lit(W.coop())); add('basket', W.eggBasket());
for (const k of ['white', 'brown']) for (const p of ['idle', 'walk0', 'walk1', 'peck0', 'peck1']) add(`hen-${k}-${p}`, W.hen(k, p));
add('chick', W.chick('idle')); add('chick-w', W.chick('walk'));
for (const p of ['sit', 'walk0', 'walk1', 'sleep']) add(`cat-${p}`, W.cat(p));
add('bob0', W.bobber(false)); add('bob1', W.bobber(true));
add('track', W.fishTrack()); add('zone', W.fishZone()); add('meter', W.fishMeter());
add('crystalP', W.caveCrystal(R.purple, 1)); add('crystalB', W.caveCrystal(R.water, 2)); add('cmush', W.caveMushroom());
writePNG('.100x/art/wild-props.png', sheet(a, { cols: 8, scale: 3 }));
const t = [];
const ta = (name, img) => t.push({ name, img });
for (let v = 0; v < 4; v++) ta('floor' + v, W.caveFloor(v, 0));
for (let m = 1; m < 8; m++) ta('fm' + m, W.caveFloor(0, m));
for (let v = 0; v < 3; v++) ta('mass' + v, W.caveMass(v));
for (let v = 0; v < 3; v++) ta('face' + v, W.caveFace(v));
ta('hole', W.caveHole()); ta('up', W.caveLadderUp());
writePNG('.100x/art/wild-cave.png', sheet(t, { cols: 8, scale: 4 }));
console.log('ok');
