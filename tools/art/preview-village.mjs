import { writePNG } from './png.mjs';
import { sheet } from './atlas.mjs';
import { R } from './palette.mjs';
import * as V from './gen/village.mjs';
import * as N from './gen/npcs.mjs';
import * as C from './gen/characters.mjs';
const lit = (o) => { const i = o.day.clone(); i.blit(o.glow, 0, 0); return i; };
const b = [];
const add = (name, img) => b.push({ name, img });
add('store', lit(V.store())); add('cafe', lit(V.cafe())); add('smithy', lit(V.smithy())); add('hall', lit(V.hall()));
for (let k = 0; k < 3; k++) add(`home${k}`, V.home(k).day);
writePNG('.100x/art/village-buildings.png', sheet(b, { cols: 4, scale: 3 }));
const p = [];
const pa = (name, img) => p.push({ name, img });
pa('shrine0', V.shrine(0).day); pa('shrine3', lit(V.shrine(3))); pa('shrine7', lit(V.shrine(7)));
pa('fount0', V.fountain(0)); pa('fount1', V.fountain(1)); pa('bench', V.bench()); pa('notice', V.noticeBoard());
pa('stall', V.stall()); pa('stallb', V.stall(R.blue, R.cream)); pa('barrel', V.barrel()); pa('crate', V.crate()); pa('well', V.well()); pa('hay', V.hayBale());
pa('scare', V.scarecrow()); pa('sign', V.signpost('FARM', 'left')); pa('sign2', V.signpost('LAKE', 'right'));
for (const s of ['spring', 'summer', 'fall', 'winter']) pa('bunt-' + s, V.bunting(s));
for (const n of N.NPCS) pa(n.id, N.portrait(n.spec));
for (const n of N.NPCS) pa(n.id + '-w', C.frame(n.spec, 'down', C.WALK[1]));
writePNG('.100x/art/village-props.png', sheet(p, { cols: 7, scale: 3 }));
console.log('ok');
