for (const [ch, gl] of Object.entries(GLYPHS)) {
  const w = gl.rows[0].length;
  gl.rows.forEach((r, i) => {
    if (r.length !== w) throw new Error(`font: glyph "${ch}" row ${i} is ${r.length} wide, expected ${w}`);
  });
  gl.w = w;
  gl.h = gl.rows.length;
}

export const LINE = 11;     // line height in pixels
export const BASE = 7;      // baseline row
export const SPACE_W = 3;
export const GAP = 1;       // pixels between glyphs

export function glyphImg(ch, color = 0xffffff) {
  const gl = GLYPHS[ch];
  if (!gl) return null;
  const img = new Img(gl.w, gl.y + gl.h);
  gl.rows.forEach((r, j) => [...r].forEach((c, i) => { if (c === '#') img.set(i, gl.y + j, color); }));
  return img;
}

export function advance(ch) {
  if (ch === ' ') return SPACE_W + GAP;
  const gl = GLYPHS[ch] || GLYPHS['?'];
  return gl.w + GAP;
}

export function textWidth(str) {
  let w = 0;
  for (const ch of str) w += advance(ch);
  return Math.max(0, w - GAP);
}

// Draw text onto an Img. Returns the width drawn.
export function drawText(img, x, y, str, color = 0xffffff, o = {}) {
  let cx = x;
  for (const ch of str) {
    if (ch === ' ') { cx += SPACE_W + GAP; continue; }
    const gl = GLYPHS[ch] || GLYPHS['?'];
    if (o.shadow !== undefined) {
      gl.rows.forEach((r, j) => [...r].forEach((c, i) => { if (c === '#') img.set(cx + i + 1, y + gl.y + j + 1, o.shadow); }));
    }
    gl.rows.forEach((r, j) => [...r].forEach((c, i) => { if (c === '#') img.set(cx + i, y + gl.y + j, color); }));
    cx += gl.w + GAP;
  }
  return cx - x - GAP;
}

// Build a bitmap font atlas (white glyphs, optional 1px outline) and its BMFont XML.
export function buildFont({ outline = null, name = 'hollow' } = {}) {
  const chars = Object.keys(GLYPHS).filter((c) => c !== ' ');
  const pad = outline !== null ? 1 : 0;
  const cellW = Math.max(...chars.map((c) => GLYPHS[c].w)) + pad * 2 + 2;
  const cellH = 9 + pad * 2 + 2;
  const cols = 16;
  const rows = Math.ceil(chars.length / cols);
  const W = cols * cellW, H = rows * cellH;
  const atlas = new Img(W, H);
  const entries = [];
  chars.forEach((ch, idx) => {
    const cx = (idx % cols) * cellW + 1, cy = Math.floor(idx / cols) * cellH + 1;
    const gl = GLYPHS[ch];
    const tile = new Img(gl.w + pad * 2, gl.h + pad * 2);
    gl.rows.forEach((r, j) => [...r].forEach((c, i) => { if (c === '#') tile.set(i + pad, j + pad, 0xffffff); }));
    if (outline !== null) tile.outline(outline, { diag: true });
    atlas.blit(tile, cx, cy);
    entries.push({
      id: ch.codePointAt(0), x: cx, y: cy, w: tile.w, h: tile.h,
      xoffset: -pad, yoffset: gl.y - pad, xadvance: gl.w + GAP,
    });
  });
  entries.push({ id: 32, x: 0, y: 0, w: 0, h: 0, xoffset: 0, yoffset: 0, xadvance: SPACE_W + GAP });
  const xml = [
    '<?xml version="1.0"?>',
    '<font>',
    `  <info face="${name}" size="9" bold="0" italic="0" charset="" unicode="1" stretchH="100" smooth="0" aa="0" padding="0,0,0,0" spacing="0,0" outline="0"/>`,
    `  <common lineHeight="${LINE}" base="${BASE}" scaleW="${W}" scaleH="${H}" pages="1" packed="0"/>`,
    '  <pages>',
    `    <page id="0" file="${name}.png"/>`,
    '  </pages>',
    `  <chars count="${entries.length}">`,
    ...entries.map((e) => `    <char id="${e.id}" x="${e.x}" y="${e.y}" width="${e.w}" height="${e.h}" xoffset="${e.xoffset}" yoffset="${e.yoffset}" xadvance="${e.xadvance}" page="0" chnl="15"/>`),
    '  </chars>',
    '</font>',
  ].join('\n');
  return { atlas, xml };
}
